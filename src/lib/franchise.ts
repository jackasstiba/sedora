/** タイトルにマッチした作品グループ（[表示名, ...エイリアス]）をすべて返す */
export function matchFranchises(title: string): string[][] {
  return FRANCHISES.filter((group) =>
    group.some((alias) => title.includes(alias))
  );
}

/** 関連検索用：マッチした作品の全エイリアス（重複除去） */
export function franchiseAliases(title: string): string[] {
  const set = new Set<string>();
  for (const group of matchFranchises(title)) for (const a of group) set.add(a);
  return [...set];
}

/** セクション見出し用：最初にマッチした作品の表示名（無ければ null） */
export function franchiseLabel(title: string): string | null {
  const groups = matchFranchises(title);
  return groups.length ? groups[0][0] : null;
}
