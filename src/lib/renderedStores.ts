/**
 * 「受付中ストア」節の1行の表示テキストを見て、締切が過去なら理由を返す（問題なければ null）。
 *
 * ・見るのは締切表記（"〜8/17 20:00"）だけ。受付開始表記（"8/20 00:00〜"）は締切ではない。
 * ・"〜本日 12:00" / "〜明日 17:00" は表示時に today から作られるので常に正しい＝対象外。
 * ・年は「基準日にいちばん近い年」で解釈する（年跨ぎで 1/5 を過去と誤判定しないため）。
 *   解釈は date.ts の parseDisplayedDate と同じ規則を使う（呼び出し側から渡す）。
 */
export function closedStoreRowProblem(
  rowText: string,
  today: Date,
  parseDate: (label: string, today: Date) => Date | null
): string | null {
  const t = rowText.replace(/\s+/g, " ").trim();
  const m = t.match(/〜\s*(\d{1,2}\/\d{1,2})/);
  if (!m) return null;
  const d = parseDate(m[1], today);
  if (!d || d.getTime() >= today.getTime()) return null;
  return `締切 ${m[1]} は過去なのに「受付中ストア」に並んでいる: ${t.slice(0, 44)}`;
}
