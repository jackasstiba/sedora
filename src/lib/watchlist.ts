/** 「ゼロの層」を数えた結果（表示用）。 */
export type WatchHit = { word: string; why: string; hits: number };

/**
 * 各語の掲載件数を数える。`match` にはサイトの検索と同じ述語を渡すこと
 * （`(title, word) => matchesQuery(title, word)`）。ここで独自の正規化を書かない。
 */
export function countWatchlist(
  titles: string[],
  match: (title: string, word: string) => boolean
): WatchHit[] {
  return WATCHLIST.map(({ word, why }) => ({
    word,
    why,
    hits: titles.reduce((n, t) => n + (match(t, word) ? 1 : 0), 0),
  }));
}
